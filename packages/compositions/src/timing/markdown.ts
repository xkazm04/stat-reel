/**
 * TIMING.md renderer: the review note written next to `timing-plan.json` before any render
 * (format of the box prototype's TIMING-search-box-wars-v2.md). Pure string output.
 */
import { type TimingPlan, planSha256 } from "@statreel/schemas";

const sec = (frames: number, fps: number): string => (frames / fps).toFixed(1);

export function renderTimingMd(plan: TimingPlan, opts: { title?: string } = {}): string {
  const { sections: s, strategy: g, fps } = plan;
  const first = plan.periods[0] ?? "";
  const last = plan.periods[plan.periods.length - 1] ?? "";
  const row = (name: string, from: number, to: number) =>
    `| ${name} | ${from}-${to} | ${sec(from, fps)}-${sec(to, fps)} |`;
  const lines: string[] = [];
  lines.push(`# Timing plan: ${opts.title ?? "data race"}`);
  lines.push("");
  lines.push(
    `Generated by \`computeTimingPlan\` (@statreel/compositions) **before** rendering. sha256 \`${planSha256(plan)}\`.`,
    "The composition reads the plan and maps frame -> period through a monotone cubic time map, so speed never jumps.",
    "",
    "## Strategy",
    `1. **Measure change density per ${g.unit}**: \`score = sum of weighted rank inversions among the visible top ${g.top_n} (row weight 1/(1+0.18 x row), using the order the viewer sees) + ${g.weights.entry} x entries/exits + sum of |delta value| / ${g.axis_max} (bar movement on the axis) + ${g.weights.base} base\`.`,
    `2. **Frames proportional to score**: clamped to ${g.min_frames}-${g.max_frames} frames per ${g.unit}, Gaussian-smoothed (sigma = ${g.sigma}), renormalised to the timeline budget (${s.timeline_end - s.hook_end} frames = ${sec(s.timeline_end - s.hook_end, fps)} s).`,
    `3. **Dwell bumps** (Gaussian, extra frames) around the events so the cards can be read.`,
    `4. **Order**: ${g.order}.${g.order_label ? ` Labelled on screen: "${g.order_label}".` : ""}`,
    `5. **Evenness** (coefficient of variation of changes per second across groups): ${plan.evenness.cv_uniform} with uniform time, ${plan.evenness.cv_warped_ex_dwell} warped (excluding the deliberate dwell), ${plan.evenness.cv_warped_incl_dwell} including dwell.`,
    "",
    `## Sections (${fps} fps, ${s.total} frames = ${sec(s.total, fps)} s)`,
    "| Section | Frames | Seconds |",
    "|---|---|---|",
    row("Hook (question + players, no answer)", 0, s.hook_end),
    row(`Timeline ${first} -> ${last} (warped)`, s.hook_end, s.timeline_end),
    row("Winner spotlight", s.timeline_end, s.spotlight_end),
    row("Like & subscribe", s.spotlight_end, s.like_end),
    row("Powered by StatReel (Frame Stat)", s.like_end, s.total),
    "",
    "## Per group: change score vs time spent",
    "| Group | Change score | Actual s | Changes/s, uniform time | Changes/s, warped (ex dwell) |",
    "|---|---|---|---|---|",
    ...plan.per_group.map(
      (r) => `| ${r.group} | ${r.change_score} | ${r.seconds} | ${r.changes_per_sec_uniform} | ${r.changes_per_sec_ex_dwell} |`,
    ),
    "",
    "## Events (dwell frames added; each card lives 120 frames, side reveal alternating left/right)",
    "| Event | Period | Dwell (frames) | Card start frame | Time |",
    "|---|---|---|---|---|",
    ...plan.events.map(
      (e) =>
        `| ${e.label} (\`${e.id}\`) | ${plan.periods[e.period] ?? e.period} | ${e.dwell} | ${e.frame} | ${sec(e.frame, fps)} s |`,
    ),
    "",
  );
  return lines.join("\n");
}
